using System.Text;

namespace UnitsNet.Modular.Generator;

internal static class BootstrapSource
{
    private static readonly string[] AllSiQuantities =
    {
        "Length",
        "Mass",
        "Duration",
        "Area",
        "Speed",
        "Acceleration",
        "Force",
        "Pressure",
        "Energy",
        "Power",
    };

    public static string Text { get; } = Create();

    private static string Create()
    {
        var writer = new StringBuilder();
        writer.AppendLine("// <auto-generated />");
        writer.AppendLine("#nullable enable");
        writer.AppendLine();
        writer.AppendLine("namespace UnitsNet.Modular.BuiltIns");
        writer.AppendLine("{");
        foreach (string quantityName in BuiltInCatalog.Names)
        {
            writer.Append("    [global::UnitsNet.Modular.QuantitySpec(\"UnitsNet.")
                .Append(quantityName)
                .AppendLine("\")]");
            writer.Append("    internal interface ").Append(quantityName).AppendLine("Spec { }");
        }

        writer.AppendLine("}");
        writer.AppendLine();
        writer.AppendLine("namespace UnitsNet.Modular.Profiles");
        writer.AppendLine("{");
        EmitProfile(writer, "AllSiProfile", AllSiQuantities);
        writer.AppendLine();
        EmitProfile(writer, "AllQuantitiesProfile", BuiltInCatalog.Names);
        writer.AppendLine("}");
        return writer.ToString();
    }

    private static void EmitProfile(StringBuilder writer, string name, IReadOnlyList<string> quantityNames)
    {
        writer.Append("    internal interface ").Append(name).AppendLine(" :");
        for (var index = 0; index < quantityNames.Count; index++)
        {
            writer.Append("        global::UnitsNet.Modular.IInclude<global::UnitsNet.Modular.BuiltIns.")
                .Append(quantityNames[index])
                .Append("Spec")
                .Append('>');
            writer.AppendLine(index == quantityNames.Count - 1 ? string.Empty : ",");
        }

        writer.AppendLine("    {");
        writer.AppendLine("    }");
    }
}
