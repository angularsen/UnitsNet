using System.Globalization;
using System.Text;

namespace UnitsNet.Modular.Generator;

internal static class QuantityEmitter
{
    public static string Emit(
        QuantitySelection selection,
        IReadOnlyList<EmittedQuantityRelation> relationships,
        QuantitySelection? affineOffset,
        IReadOnlyDictionary<string, QuantitySelection> selectionsBySemanticId)
    {
        QuantityDefinition quantity = selection.Definition;
        string unitTypeName = quantity.Name + "Unit";
        bool unitsNetCompatibility = quantity.TargetNamespace == "UnitsNet";
        string unitType = unitsNetCompatibility
            ? "global::UnitsNet.Units." + unitTypeName
            : unitTypeName;
        var writer = new StringBuilder();

        writer.AppendLine("// <auto-generated />");
        writer.AppendLine("#nullable enable");
        writer.AppendLine();
        if (unitsNetCompatibility)
        {
            writer.AppendLine("namespace UnitsNet.Units");
            writer.AppendLine("{");
        }
        else
        {
            writer.Append("namespace ").Append(quantity.TargetNamespace).AppendLine(";");
            writer.AppendLine();
        }

        writer.Append("public enum ").Append(unitTypeName).AppendLine();
        writer.AppendLine("{");
        IReadOnlyDictionary<string, int> definitionIndexes = quantity.Units
            .Select((unit, index) => new { unit.SingularName, Index = index })
            .ToDictionary(item => item.SingularName, item => item.Index, StringComparer.Ordinal);
        foreach (UnitDefinition unit in selection.Units)
        {
            int definitionIndex = definitionIndexes[unit.SingularName];
            int enumValue = BuiltInUnitEnumValues.TryGet(quantity.SemanticId, unit.SingularName, out int stableValue)
                ? stableValue
                : definitionIndex + 1;
            writer.Append("    ").Append(unit.SingularName).Append(" = ")
                .Append(enumValue.ToString(CultureInfo.InvariantCulture)).AppendLine(",");
        }

        writer.AppendLine("}");
        writer.AppendLine();
        if (unitsNetCompatibility)
        {
            writer.AppendLine("}");
            writer.AppendLine();
            writer.AppendLine("namespace UnitsNet");
            writer.AppendLine("{");
        }

        writer.Append("public readonly partial struct ").Append(quantity.Name).Append(" : ");
        if (quantity.IsAffine)
        {
            writer.Append("global::UnitsNet.IAffineQuantity<").Append(quantity.Name).Append(", ")
                .Append(unitType).Append(", ").Append(QuantityType(affineOffset!.Definition)).Append(">, ");
        }
        else
        {
            string capabilityInterface = quantity.IsLogarithmic
                ? "global::UnitsNet.ILogarithmicQuantity<"
                : "global::UnitsNet.ILinearQuantity<";
            writer.Append(capabilityInterface).Append(quantity.Name).Append(", ").Append(unitType).Append(">, ");
        }
        writer
            .Append("global::System.IEquatable<").Append(quantity.Name).Append(">, ")
            .Append("global::System.IComparable<").Append(quantity.Name).Append(">, ")
            .AppendLine("global::System.IComparable");
        writer.AppendLine("#if NET8_0_OR_GREATER");
        writer.Append("    , global::System.IParsable<").Append(quantity.Name).AppendLine(">");
        writer.Append("    , global::System.Numerics.IComparisonOperators<").Append(quantity.Name).Append(", ").Append(quantity.Name).AppendLine(", bool>");
        if (!quantity.IsAffine)
        {
            writer.Append("    , global::System.Numerics.IDivisionOperators<").Append(quantity.Name).Append(", ")
                .Append(quantity.Name).AppendLine(", double>");
        }
        writer.AppendLine("#endif");
        writer.AppendLine("{");
        writer.Append("    private static readonly QuantityMetadata Metadata = new QuantityMetadata();").AppendLine();
        writer.AppendLine("    private readonly double _value;");
        writer.Append("    private readonly ").Append(unitType).AppendLine(" _unit;");
        writer.AppendLine();
        writer.Append("    public ").Append(quantity.Name).Append("(double value, ").Append(unitType).AppendLine(" unit)");
        writer.AppendLine("    {");
        writer.AppendLine("        _value = value;");
        writer.AppendLine("        _unit = unit;");
        writer.AppendLine("        _ = global::UnitsNet.Modular.SourceGen.QuantityOperations.GetBaseValue(value, unit, Metadata);");
        writer.AppendLine("    }");
        writer.Append("    public ").Append(quantity.Name)
            .AppendLine("(double value, global::UnitsNet.UnitSystem unitSystem)");
        writer.AppendLine("        : this(value, global::UnitsNet.Modular.SourceGen.QuantityOperations.GetUnit(unitSystem, Metadata))");
        writer.AppendLine("    {");
        writer.AppendLine("    }");
        writer.AppendLine();
        writer.Append("    public static ").Append(quantity.Name).Append(" From(double value, ")
            .Append(unitType).AppendLine(" unit) => new(value, unit);");
        writer.Append("    public static ").Append(quantity.Name)
            .AppendLine(" From(double value, global::UnitsNet.UnitSystem unitSystem) => new(value, unitSystem);");
        writer.Append("    public static double Convert(double value, ").Append(unitType).Append(" fromUnit, ")
            .Append(unitType).AppendLine(" toUnit) =>");
        writer.AppendLine("        global::UnitsNet.Modular.SourceGen.QuantityOperations.Convert(value, fromUnit, toUnit, Metadata);");
        writer.AppendLine();
        writer.AppendLine("    public double Value => _value;");
        writer.Append("    public ").Append(unitType).AppendLine(" Unit => _unit == default ? Info.BaseUnit.Value : _unit;");
        writer.Append("    public static global::UnitsNet.QuantityInfo<").Append(quantity.Name).Append(", ")
            .Append(unitType).Append("> Info { get; } = new(")
            .Append("new global::UnitsNet.QuantityId(\"").Append(Escape(quantity.SemanticId))
            .AppendLine("\"), Metadata);");
        writer.Append("    internal static ").Append(unitType).AppendLine(" BaseUnit => Info.BaseUnit.Value;");
        writer.Append("    public static ").Append(quantity.Name).AppendLine(" Zero => From(0, Info.BaseUnit.Value);");
        if (quantity.IsLogarithmic)
        {
            writer.Append("    public static double LogarithmicScalingFactor => ")
                .Append((10 * quantity.LogarithmicScalingFactor).ToString("R", CultureInfo.InvariantCulture))
                .AppendLine(";");
        }

        writer.AppendLine("    internal double BaseValue => global::UnitsNet.Modular.SourceGen.QuantityOperations.GetBaseValue(_value, Unit, Metadata);");
        writer.AppendLine();

        foreach (UnitDefinition unit in selection.Units)
        {
            writer.Append("    public static ").Append(quantity.Name).Append(" From").Append(unit.PluralName).Append("(double value) => new ")
                .Append(quantity.Name).Append("(value, ").Append(unitType).Append('.').Append(unit.SingularName).AppendLine(");");
            writer.Append("    public double ").Append(unit.PluralName).Append(" => As(").Append(unitType).Append('.').Append(unit.SingularName).AppendLine(");");
        }

        writer.AppendLine();
        writer.Append("    public double As(").Append(unitType).AppendLine(" unit) =>");
        writer.AppendLine("        Convert(_value, Unit, unit);");
        writer.AppendLine("    public double As(global::UnitsNet.UnitSystem unitSystem) =>");
        writer.AppendLine("        As(global::UnitsNet.Modular.SourceGen.QuantityOperations.GetUnit(unitSystem, Metadata));");
        writer.AppendLine();
        writer.Append("    public ").Append(quantity.Name).Append(" ToUnit(").Append(unitType).AppendLine(" unit) => new(As(unit), unit);");
        writer.Append("    public ").Append(quantity.Name)
            .AppendLine(" ToUnit(global::UnitsNet.UnitSystem unitSystem)");
        writer.AppendLine("    {");
        writer.AppendLine("        var unit = global::UnitsNet.Modular.SourceGen.QuantityOperations.GetUnit(unitSystem, Metadata);");
        writer.Append("        return new ").Append(quantity.Name).AppendLine("(As(unit), unit);");
        writer.AppendLine("    }");
        writer.AppendLine();
        writer.Append("    public static string GetAbbreviation(").Append(unitType).AppendLine(" unit) =>");
        writer.AppendLine("        GetAbbreviation(unit, null);");
        writer.Append("    public static string GetAbbreviation(").Append(unitType)
            .AppendLine(" unit, global::System.IFormatProvider? formatProvider) =>");
        writer.AppendLine("        global::UnitsNet.Modular.SourceGen.QuantityOperations.GetAbbreviation(unit, formatProvider, Metadata);");
        writer.AppendLine();
        writer.Append("    public static ").Append(quantity.Name).AppendLine(" Parse(string text) => Parse(text, null);");
        writer.Append("    public static ").Append(quantity.Name).AppendLine(" Parse(string text, global::System.IFormatProvider? formatProvider)");
        writer.AppendLine("    {");
        writer.AppendLine("        if (!global::UnitsNet.Modular.SourceGen.QuantityOperations.TryParse(text, formatProvider, Metadata, out double value, out var unit))");
        writer.AppendLine("        {");
        writer.Append("            throw new global::System.FormatException(\"Could not parse ").Append(Escape(quantity.Name)).AppendLine(".\");");
        writer.AppendLine("        }");
        writer.AppendLine();
        writer.Append("        return new ").Append(quantity.Name).AppendLine("(value, unit);");
        writer.AppendLine("    }");
        writer.AppendLine();
        writer.Append("    public static bool TryParse(string? text, out ").Append(quantity.Name).AppendLine(" quantity)");
        writer.AppendLine("    {");
        writer.AppendLine("        if (global::UnitsNet.Modular.SourceGen.QuantityOperations.TryParse(text, null, Metadata, out double value, out var unit))");
        writer.AppendLine("        {");
        writer.Append("            quantity = new ").Append(quantity.Name).AppendLine("(value, unit);");
        writer.AppendLine("            return true;");
        writer.AppendLine("        }");
        writer.AppendLine();
        writer.AppendLine("        quantity = default;");
        writer.AppendLine("        return false;");
        writer.AppendLine("    }");
        writer.AppendLine("#if NET8_0_OR_GREATER");
        writer.Append("    public static bool TryParse(string? text, global::System.IFormatProvider? formatProvider, out ").Append(quantity.Name).AppendLine(" quantity)");
        writer.AppendLine("    {");
        writer.AppendLine("        if (global::UnitsNet.Modular.SourceGen.QuantityOperations.TryParse(text, formatProvider, Metadata, out double value, out var unit))");
        writer.AppendLine("        {");
        writer.Append("            quantity = new ").Append(quantity.Name).AppendLine("(value, unit);");
        writer.AppendLine("            return true;");
        writer.AppendLine("        }");
        writer.AppendLine();
        writer.AppendLine("        quantity = default;");
        writer.AppendLine("        return false;");
        writer.AppendLine("    }");
        writer.AppendLine("#endif");
        writer.AppendLine();
        writer.Append("    public static ").Append(unitType).AppendLine(" ParseUnit(string text) => ParseUnit(text, null);");
        writer.Append("    public static ").Append(unitType)
            .AppendLine(" ParseUnit(string text, global::System.IFormatProvider? formatProvider)");
        writer.AppendLine("    {");
        writer.AppendLine("        if (TryParseUnit(text, formatProvider, out var unit))");
        writer.AppendLine("        {");
        writer.AppendLine("            return unit;");
        writer.AppendLine("        }");
        writer.AppendLine();
        writer.Append("        throw new global::System.FormatException(\"Could not parse ").Append(Escape(unitTypeName))
            .AppendLine(".\");");
        writer.AppendLine("    }");
        writer.Append("    public static bool TryParseUnit(string? text, out ").Append(unitType)
            .AppendLine(" unit) => TryParseUnit(text, null, out unit);");
        writer.Append("    public static bool TryParseUnit(string? text, global::System.IFormatProvider? formatProvider, out ")
            .Append(unitType).AppendLine(" unit) =>");
        writer.AppendLine("        global::UnitsNet.Modular.SourceGen.QuantityOperations.TryParseUnit(text, formatProvider, Metadata, out unit);");
        writer.AppendLine();
        writer.Append("    public int CompareTo(").Append(quantity.Name).AppendLine(" other) => BaseValue.CompareTo(other.BaseValue);");
        writer.Append("    public int CompareTo(object? obj) => obj is ").Append(quantity.Name)
            .AppendLine(" other ? CompareTo(other) : throw new global::System.ArgumentException(\"Object must be the same quantity type.\", nameof(obj));");
        writer.Append("    public bool Equals(").Append(quantity.Name)
            .AppendLine(" other) => BaseValue.Equals(other.BaseValue);");
        writer.Append("    public override bool Equals(object? obj) => obj is ").Append(quantity.Name).AppendLine(" other && Equals(other);");
        writer.AppendLine("    public override int GetHashCode() => BaseValue.GetHashCode();");
        writer.AppendLine("    public override string ToString() => ToString(null, null);");
        writer.AppendLine("    public string ToString(global::System.IFormatProvider? formatProvider) => ToString(null, formatProvider);");
        writer.AppendLine("    public string ToString(string? format) => ToString(format, null);");
        writer.AppendLine("    public string ToString(string? format, global::System.IFormatProvider? formatProvider) =>");
        writer.AppendLine("        global::UnitsNet.Modular.SourceGen.QuantityOperations.Format(_value, Unit, format, formatProvider, Metadata);");
        writer.AppendLine();
        if (quantity.IsLogarithmic)
        {
            EmitLogarithmicOperators(writer, quantity.Name, quantity.LogarithmicScalingFactor);
        }
        else if (quantity.IsAffine)
        {
            EmitAffineOperators(writer, selection, affineOffset!);
        }
        else
        {
            writer.Append("    public static ").Append(quantity.Name).Append(" operator -(").Append(quantity.Name)
                .AppendLine(" quantity) => new(-quantity.Value, quantity.Unit);");
            writer.Append("    public static ").Append(quantity.Name).Append(" operator +(").Append(quantity.Name).Append(" left, ").Append(quantity.Name)
                .AppendLine(" right) => new(left.Value + right.As(left.Unit), left.Unit);");
            writer.Append("    public static ").Append(quantity.Name).Append(" operator -(").Append(quantity.Name).Append(" left, ").Append(quantity.Name)
                .AppendLine(" right) => new(left.Value - right.As(left.Unit), left.Unit);");
            writer.Append("    public static ").Append(quantity.Name).Append(" operator *(").Append(quantity.Name)
                .AppendLine(" quantity, double scalar) => new(quantity.Value * scalar, quantity.Unit);");
            writer.Append("    public static ").Append(quantity.Name).Append(" operator *(double scalar, ").Append(quantity.Name)
                .AppendLine(" quantity) => quantity * scalar;");
            writer.Append("    public static ").Append(quantity.Name).Append(" operator /(").Append(quantity.Name)
                .AppendLine(" quantity, double scalar) => new(quantity.Value / scalar, quantity.Unit);");
            writer.Append("    public static double operator /(").Append(quantity.Name).Append(" left, ")
                .Append(quantity.Name).AppendLine(" right) => left.Value / right.As(left.Unit);");
        }

        writer.Append("    public static bool operator ==(").Append(quantity.Name).Append(" left, ").Append(quantity.Name).AppendLine(" right) => left.Equals(right);");
        writer.Append("    public static bool operator !=(").Append(quantity.Name).Append(" left, ").Append(quantity.Name).AppendLine(" right) => !left.Equals(right);");
        writer.Append("    public static bool operator <(").Append(quantity.Name).Append(" left, ").Append(quantity.Name).AppendLine(" right) => left.CompareTo(right) < 0;");
        writer.Append("    public static bool operator >(").Append(quantity.Name).Append(" left, ").Append(quantity.Name).AppendLine(" right) => left.CompareTo(right) > 0;");
        writer.Append("    public static bool operator <=(").Append(quantity.Name).Append(" left, ").Append(quantity.Name).AppendLine(" right) => left.CompareTo(right) <= 0;");
        writer.Append("    public static bool operator >=(").Append(quantity.Name).Append(" left, ").Append(quantity.Name).AppendLine(" right) => left.CompareTo(right) >= 0;");

        BuiltInAugmentationEmitter.Emit(writer, selection, unitType, selectionsBySemanticId);
        EmitRelationships(writer, relationships);

        writer.AppendLine();
        writer.Append("    private sealed class QuantityMetadata : global::UnitsNet.Modular.SourceGen.IQuantityMetadata<")
            .Append(quantity.Name).Append(", ").Append(unitType).AppendLine(">");
        writer.AppendLine("    {");
        writer.Append("        private static readonly global::UnitsNet.UnitInfo<").Append(unitType).AppendLine(">[] AllUnits =");
        writer.AppendLine("        {");
        foreach (UnitDefinition unit in selection.Units)
        {
            writer.Append("            new global::UnitsNet.UnitInfo<").Append(unitType).Append(">(")
                .Append(unitType).Append('.').Append(unit.SingularName).Append(", \"").Append(Escape(unit.SingularName))
                .Append("\", \"").Append(Escape(unit.PluralName)).Append("\", ");
            EmitBaseUnits(writer, unit.BaseUnits);
            foreach (UnitLocalizationDefinition localization in unit.Localizations)
            {
                writer.Append(", new global::UnitsNet.UnitLocalization(\"").Append(Escape(localization.Culture)).Append('"');
                foreach (string abbreviation in localization.Abbreviations)
                {
                    writer.Append(", \"").Append(Escape(abbreviation)).Append('"');
                }

                writer.Append(')');
            }

            writer.AppendLine("),");
        }

        writer.AppendLine("        };");
        writer.AppendLine();
        writer.Append("        public string Name => \"").Append(Escape(quantity.Name)).AppendLine("\";");
        writer.Append("        public ").Append(unitType).Append(" BaseUnit => ").Append(unitType).Append('.').Append(quantity.BaseUnit).AppendLine(";");
        writer.Append("        public global::System.Collections.Generic.IReadOnlyList<global::UnitsNet.UnitInfo<")
            .Append(unitType).AppendLine(">> Units => AllUnits;");
        BaseDimensionsDefinition dimensions = quantity.BaseDimensions;
        writer.AppendLine("        public global::UnitsNet.BaseDimensions BaseDimensions { get; } = new(");
        writer.Append("            ").Append(dimensions.Length.ToString(CultureInfo.InvariantCulture)).Append(", ")
            .Append(dimensions.Mass.ToString(CultureInfo.InvariantCulture)).Append(", ")
            .Append(dimensions.Time.ToString(CultureInfo.InvariantCulture)).Append(", ")
            .Append(dimensions.Current.ToString(CultureInfo.InvariantCulture)).Append(", ")
            .Append(dimensions.Temperature.ToString(CultureInfo.InvariantCulture)).Append(", ")
            .Append(dimensions.Amount.ToString(CultureInfo.InvariantCulture)).Append(", ")
            .Append(dimensions.LuminousIntensity.ToString(CultureInfo.InvariantCulture)).AppendLine(");");
        writer.AppendLine();
        writer.Append("        public double ToBase(double x, ").Append(unitType).AppendLine(" unit) => unit switch");
        writer.AppendLine("        {");
        foreach (UnitDefinition unit in selection.Units)
        {
            writer.Append("            ").Append(unitType).Append('.').Append(unit.SingularName).Append(" => ")
                .Append(unit.FromUnitToBaseExpression).AppendLine(",");
        }

        writer.Append("            _ => throw new global::System.ArgumentOutOfRangeException(nameof(unit), unit, \"Unit is not generated for ")
            .Append(Escape(quantity.Name)).AppendLine(".\"),");
        writer.AppendLine("        };");
        writer.AppendLine();
        writer.Append("        public double FromBase(double x, ").Append(unitType).AppendLine(" unit) => unit switch");
        writer.AppendLine("        {");
        foreach (UnitDefinition unit in selection.Units)
        {
            writer.Append("            ").Append(unitType).Append('.').Append(unit.SingularName).Append(" => ")
                .Append(unit.FromBaseToUnitExpression).AppendLine(",");
        }

        writer.Append("            _ => throw new global::System.ArgumentOutOfRangeException(nameof(unit), unit, \"Unit is not generated for ")
            .Append(Escape(quantity.Name)).AppendLine(".\"),");
        writer.AppendLine("        };");
        writer.AppendLine();
        writer.Append("        public ").Append(quantity.Name)
            .AppendLine(" Parse(string text, global::System.IFormatProvider? formatProvider) =>");
        writer.Append("            ").Append(quantity.Name).AppendLine(".Parse(text, formatProvider);");
        writer.Append("        public bool TryParse(string? text, global::System.IFormatProvider? formatProvider, out ")
            .Append(quantity.Name).AppendLine(" quantity) =>");
        writer.Append("            ").Append(quantity.Name).AppendLine(".TryParse(text, formatProvider, out quantity);");
        writer.AppendLine("    }");
        writer.AppendLine("}");
        if (unitsNetCompatibility)
        {
            writer.AppendLine("}");
        }

        return writer.ToString();
    }

    private static void EmitRelationships(
        StringBuilder writer,
        IReadOnlyList<EmittedQuantityRelation> relationships)
    {
        foreach (EmittedQuantityRelation relationship in relationships)
        {
            if (relationship.Operator is "*" or "/" &&
                relationship.Result is null &&
                relationship.Left is not null &&
                relationship.Right is not null)
            {
                string scalarLeftValue = ConversionExpression.Substitute(
                    relationship.LeftUnit!.FromBaseToUnitExpression,
                    "left.BaseValue");
                string scalarRightValue = ConversionExpression.Substitute(
                    relationship.RightUnit!.FromBaseToUnitExpression,
                    "right.BaseValue");
                writer.Append("    public static double operator *(")
                    .Append(QuantityType(relationship.Left.Definition)).Append(" left, ")
                    .Append(QuantityType(relationship.Right.Definition)).Append(" right) => (")
                    .Append(scalarLeftValue).Append(") ").Append(relationship.Operator).Append(" (")
                    .Append(scalarRightValue).AppendLine(");");
                continue;
            }

            if (relationship.Operator == "/" &&
                relationship.Left is null &&
                relationship.Result is not null &&
                relationship.Right is not null)
            {
                string scalarRightValue = ConversionExpression.Substitute(
                    relationship.RightUnit!.FromBaseToUnitExpression,
                    "right.BaseValue");
                string scalarResultValue = "left / (" + scalarRightValue + ")";
                writer.Append("    public static ").Append(QuantityType(relationship.Result.Definition))
                    .Append(" operator /(double left, ")
                    .Append(QuantityType(relationship.Right.Definition)).Append(" right) => ")
                    .Append(ConstructFromRelationUnit(
                        relationship.Result,
                        relationship.ResultUnit!,
                        scalarResultValue))
                    .AppendLine(";");
                continue;
            }

            QuantitySelection left = relationship.Left!;
            QuantitySelection right = relationship.Right!;
            UnitDefinition leftUnit = relationship.LeftUnit!;
            UnitDefinition rightUnit = relationship.RightUnit!;
            string leftType = QuantityType(left.Definition);
            string rightType = QuantityType(right.Definition);
            string leftValue = ConversionExpression.Substitute(
                leftUnit.FromBaseToUnitExpression,
                relationship.Operator == "inverse" ? "BaseValue" : "left.BaseValue");
            string rightValue = ConversionExpression.Substitute(
                rightUnit.FromBaseToUnitExpression,
                "right.BaseValue");
            if (relationship.Operator == "inverse")
            {
                string inverseValue = "1 / (" + leftValue + ")";
                writer.Append("    public ").Append(rightType).Append(" Inverse() => ")
                    .Append(ConstructFromRelationUnit(
                        right,
                        rightUnit,
                        inverseValue))
                    .AppendLine(";");
                continue;
            }

            QuantitySelection result = relationship.Result!;
            string relationValue = "(" + leftValue + ") " + relationship.Operator + " (" + rightValue + ")";
            writer.Append("    public static ").Append(QuantityType(result.Definition)).Append(" operator ")
                .Append(relationship.Operator).Append('(').Append(leftType).Append(" left, ")
                .Append(rightType).Append(" right) => ")
                .Append(ConstructFromRelationUnit(result, relationship.ResultUnit!, relationValue))
                .AppendLine(";");
        }
    }

    private static string ConstructFromRelationUnit(
        QuantitySelection result,
        UnitDefinition relationUnit,
        string value)
    {
        string baseValue = ConversionExpression.Substitute(relationUnit.FromUnitToBaseExpression, value);
        return "new " + QuantityType(result.Definition) + "(" + baseValue + ", " +
               UnitType(result.Definition) + "." + result.Definition.BaseUnit + ")";
    }

    private static string QuantityType(QuantityDefinition definition) =>
        "global::" + definition.TargetNamespace + "." + definition.Name;

    private static string UnitType(QuantityDefinition definition) =>
        definition.TargetNamespace == "UnitsNet"
            ? "global::UnitsNet.Units." + definition.Name + "Unit"
            : "global::" + definition.TargetNamespace + "." + definition.Name + "Unit";

    private static void EmitBaseUnits(StringBuilder writer, BaseUnitsDefinition baseUnits)
    {
        if (baseUnits.IsUndefined)
        {
            writer.Append("global::UnitsNet.BaseUnits.Undefined");
            return;
        }

        writer.Append("new global::UnitsNet.BaseUnits(");
        AppendBaseUnit(writer, "length", baseUnits.Length);
        AppendBaseUnit(writer, "mass", baseUnits.Mass);
        AppendBaseUnit(writer, "time", baseUnits.Time);
        AppendBaseUnit(writer, "current", baseUnits.Current);
        AppendBaseUnit(writer, "temperature", baseUnits.Temperature);
        AppendBaseUnit(writer, "amount", baseUnits.Amount);
        AppendBaseUnit(writer, "luminousIntensity", baseUnits.LuminousIntensity);
        writer.Length -= 2;
        writer.Append(')');
    }

    private static void AppendBaseUnit(StringBuilder writer, string parameterName, string? unitName)
    {
        if (unitName is not null)
        {
            writer.Append(parameterName).Append(": \"").Append(Escape(unitName)).Append("\", ");
        }
    }

    private static void EmitLogarithmicOperators(
        StringBuilder writer,
        string quantityName,
        double logarithmicScalingFactor)
    {
        string scalingFactor = (10 * logarithmicScalingFactor).ToString("R", CultureInfo.InvariantCulture);
        writer.Append("    public static ").Append(quantityName).Append(" operator -(").Append(quantityName)
            .AppendLine(" quantity) => new(-quantity.Value, quantity.Unit);");
        writer.Append("    public static ").Append(quantityName).Append(" operator +(").Append(quantityName).Append(" left, ")
            .Append(quantityName).Append(" right) => new(").Append(scalingFactor)
            .Append(" * global::System.Math.Log10(global::System.Math.Pow(10, left.Value / ")
            .Append(scalingFactor)
            .Append(") + global::System.Math.Pow(10, right.As(left.Unit) / ")
            .Append(scalingFactor).AppendLine(")), left.Unit);");
        writer.Append("    public static ").Append(quantityName).Append(" operator -(").Append(quantityName).Append(" left, ")
            .Append(quantityName).Append(" right) => new(").Append(scalingFactor)
            .Append(" * global::System.Math.Log10(global::System.Math.Pow(10, left.Value / ")
            .Append(scalingFactor)
            .Append(") - global::System.Math.Pow(10, right.As(left.Unit) / ")
            .Append(scalingFactor).AppendLine(")), left.Unit);");
        writer.AppendLine("    /// <summary>Performs logarithmic multiplication by adding the scalar to the stored logarithmic value.</summary>");
        writer.Append("    public static ").Append(quantityName).Append(" operator *(").Append(quantityName)
            .AppendLine(" quantity, double scalar) => new(quantity.Value + scalar, quantity.Unit);");
        writer.AppendLine("    /// <summary>Performs commutative logarithmic multiplication by adding the scalar to the stored logarithmic value.</summary>");
        writer.Append("    public static ").Append(quantityName).Append(" operator *(").Append("double scalar, ")
            .Append(quantityName).AppendLine(" quantity) => quantity * scalar;");
        writer.AppendLine("    /// <summary>Performs logarithmic division by subtracting the scalar from the stored logarithmic value.</summary>");
        writer.Append("    public static ").Append(quantityName).Append(" operator /(").Append(quantityName)
            .AppendLine(" quantity, double scalar) => new(quantity.Value - scalar, quantity.Unit);");
        writer.AppendLine("    /// <summary>Returns the logarithmic difference between two quantities expressed in the left operand's unit.</summary>");
        writer.Append("    public static double operator /(").Append(quantityName).Append(" left, ").Append(quantityName)
            .AppendLine(" right) => left.Value - right.As(left.Unit);");
    }

    private static void EmitAffineOperators(
        StringBuilder writer,
        QuantitySelection quantity,
        QuantitySelection offset)
    {
        string quantityType = quantity.Definition.Name;
        string offsetType = QuantityType(offset.Definition);
        string offsetBaseUnit = UnitType(offset.Definition) + "." + offset.Definition.BaseUnit;
        writer.Append("    public static ").Append(quantityType).Append(" operator +(").Append(quantityType)
            .Append(" left, ").Append(offsetType).AppendLine(" right) =>")
            .Append("        new(left.BaseValue + right.BaseValue, Info.BaseUnit.Value);").AppendLine();
        writer.Append("    public static ").Append(quantityType).Append(" operator +(").Append(offsetType)
            .Append(" left, ").Append(quantityType).AppendLine(" right) => right + left;");
        writer.Append("    public static ").Append(quantityType).Append(" operator -(").Append(quantityType)
            .Append(" left, ").Append(offsetType).AppendLine(" right) =>")
            .Append("        new(left.BaseValue - right.BaseValue, Info.BaseUnit.Value);").AppendLine();
        writer.Append("    public static ").Append(offsetType).Append(" operator -(").Append(quantityType)
            .Append(" left, ").Append(quantityType).AppendLine(" right) =>")
            .Append("        new(left.BaseValue - right.BaseValue, ").Append(offsetBaseUnit).AppendLine(");");
    }

    private static string Escape(string value) => value.Replace("\\", "\\\\").Replace("\"", "\\\"");
